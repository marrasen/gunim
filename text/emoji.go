package text

import "slices"

// drawsAsEmoji reports whether runes, one character, shows as an emoji in colours of its own: one that does by itself,
// with the variation selector or skin tone that has an emoji, or keys on a keyboard, do so.
func drawsAsEmoji(runes []rune) bool {
	if len(runes) == 0 || slices.Contains(runes, textSelector) {
		return false
	}
	if keycap(runes) {
		return slices.Contains(runes, emojiSelector)
	}
	if len(runes) > 1 && emojiBase(runes[0]) && slices.ContainsFunc(runes[1:], func(r rune) bool {
		return r == emojiSelector || r >= 0x1f3fb && r <= 0x1f3ff
	}) {
		return true
	}
	return emojiPresents(runes[0])
}

// The variation selectors that ask for an emoji as text, and as an emoji, and the key a digit may be drawn on.
const (
	textSelector  = 0xfe0e
	emojiSelector = 0xfe0f
	keycapMark    = 0x20e3
)

// keycap reports whether runes are a keycap: a digit, a number sign or an asterisk on a key.
func keycap(runes []rune) bool {
	r := runes[0]
	return (r >= '0' && r <= '9' || r == '#' || r == '*') && slices.Contains(runes, keycapMark)
}

// emojiBase reports whether r is an emoji, by itself or where it is asked for.
func emojiBase(r rune) bool { return emojiPresents(r) || inRanges(r, textEmoji) }

// emojiPresents reports whether r shows as an emoji by itself, as Unicode's Emoji_Presentation says.
func emojiPresents(r rune) bool { return inRanges(r, emojiShown) }

// inRanges reports whether r is in one of ranges, which are in order.
func inRanges(r rune, ranges [][2]rune) bool {
	if r < ranges[0][0] {
		return false
	}
	i, _ := slices.BinarySearchFunc(ranges, r, func(s [2]rune, r rune) int { return int(s[1]) - int(r) })
	return i < len(ranges) && ranges[i][0] <= r
}

